const decimal = 111; // Base 10
//111 = 1*100 + 1 * 10 + 1*1

const binario = 0b111; // Base 2
//111 = 1*4 + 1*2 + 1*1 = 7

const hexa = 0x111; // Base 16
//111 = 1*256 + 1*16 + 1*1 = 276

console.log(`111 Decimal: ${decimal}`);
console.log(`111 Binario ${binario}`);
console.log(`111 Hexa: ${hexa}`);


